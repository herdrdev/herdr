#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum UpdateChannel {
    Stable,
    Preview,
}

impl UpdateChannel {
    fn configured() -> Self {
        match crate::config::Config::load().config.update.channel {
            crate::config::UpdateChannelConfig::Stable => Self::Stable,
            crate::config::UpdateChannelConfig::Preview => Self::Preview,
        }
    }

    fn as_str(self) -> &'static str {
        match self {
            Self::Stable => "stable",
            Self::Preview => "preview",
        }
    }
}

#[derive(Debug, Clone)]
struct AssetRef {
    url: String,
    sha256: Option<String>,
    #[cfg(windows)]
    format: Option<String>,
}

impl<'de> Deserialize<'de> for AssetRef {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let value = serde_json::Value::deserialize(deserializer)?;
        match value {
            serde_json::Value::String(url) if !url.trim().is_empty() => Ok(Self {
                url: url.trim().to_string(),
                sha256: None,
                #[cfg(windows)]
                format: None,
            }),
            serde_json::Value::Object(mut object) => {
                let url = object
                    .remove("url")
                    .and_then(|value| value.as_str().map(str::to_string))
                    .ok_or_else(|| serde::de::Error::custom("asset object is missing url"))?;
                let sha256 = object
                    .remove("sha256")
                    .and_then(|value| value.as_str().map(str::to_string));
                #[cfg(windows)]
                let format = object
                    .remove("format")
                    .and_then(|value| value.as_str().map(str::to_string));
                if url.trim().is_empty() {
                    return Err(serde::de::Error::custom("asset url must not be empty"));
                }
                Ok(Self {
                    url: url.trim().to_string(),
                    sha256: sha256.filter(|value| !value.trim().is_empty()),
                    #[cfg(windows)]
                    format: format.filter(|value| !value.trim().is_empty()),
                })
            }
            _ => Err(serde::de::Error::custom(
                "asset must be a URL string or object with url",
            )),
        }
    }
}

#[cfg(windows)]
impl AssetRef {
    fn package_format(&self) -> Result<String, String> {
        let format = self
            .format
            .clone()
            .unwrap_or_else(|| {
                if self.url.to_ascii_lowercase().ends_with(".zip") {
                    "zip"
                } else {
                    "exe"
                }
                .into()
            })
            .to_ascii_lowercase();
        match format.as_str() {
            "zip" | "exe" => Ok(format),
            _ => Err(format!(
                "update manifest asset has unsupported format '{format}'"
            )),
        }
    }
}

